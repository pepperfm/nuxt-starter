import { mkdir, writeFile, chmod } from 'node:fs/promises'
import { resolve, dirname, relative, isAbsolute } from 'node:path'
import { randomBytes } from 'node:crypto'
import { spawn } from 'node:child_process'
import { context, serialize } from './context.mjs'
import { base } from './recipes/base.mjs'
import { ui } from './recipes/ui.mjs'
import { extras } from './recipes/modules.mjs'
import { data } from './recipes/data.mjs'
import { auth } from './recipes/auth.mjs'
import { queue } from './recipes/queue.mjs'
import { infra } from './recipes/infra.mjs'

export const generatorVersion = '0.1.0'
export function buildProject(options) {
  const c = context(options)
  for (const recipe of [base, ui, extras, data, auth, queue, infra]) recipe(c)
  c.pkg.engines = { bun: '>=1.3.0', node: c.has('content') ? '>=22.13.0' : '>=22.12.0' }
  for (const key of ['dependencies', 'devDependencies']) c.pkg[key] = Object.fromEntries(Object.entries(c.pkg[key]).sort(([a], [b]) => a.localeCompare(b)))
  c.file('package.json', JSON.stringify(c.pkg, null, 2))
  c.file('nuxt.config.ts', [...c.imports, '', `export default defineNuxtConfig(${serialize(c.cfg)})`].join('\n'))
  c.file('.env.example', ['# Local development defaults only; do not use these credentials on production.', ...c.env].join('\n'))
  c.file('.pepperfm-starter.json', JSON.stringify({ schemaVersion: 1, generatorVersion, ui: options.ui,
    modules: options.modules, features: options.features, database: options.features.includes('hub') ? options.database : null,
    packageManager: options.pm, runtime: 'bun', locales: options.modules.includes('i18n') ? options.locales : [],
    localDocker: options.docker, ubuntuDeployment: options.deploy }, null, 2))
  c.file('AGENTS.md', `# Project conventions\n\n- Bun is the default package manager AND production runtime; keep nitro.preset = 'bun'.\n- Docker Compose is local infrastructure only; Ubuntu production uses Bun + systemd + Nginx.\n- Keep API handlers thin: validate, authenticate, authorize, call domain logic, respond.\n- Page middleware does not protect API endpoints. Never share authenticated responses through a global cache.\n- Shared client/server schemas belong in shared/; secrets, DB clients and privileged code belong on the server.\n- Use ordinary TypeScript dependencies for workers; no Nuxt virtual aliases or request-scoped helpers there.\n- Generate database migrations through nuxt db generate, inspect and commit them. Never run db:generate in production.\n- Use explicit Redis connection URLs. Cache and durable state are different instances; sessions/queues require noeviction.\n- Keep one UI library; check .pepperfm-starter.json before adding UI dependencies.\n- Use the existing native helpers before introducing framework-shaped wrappers.\n- Run typecheck${c.has('queue') ? ', typecheck:worker' : ''}${c.has('test') ? ', test' : ''}${c.has('eslint') ? ', lint' : ''} and build after changes.\n`)
  const run = options.pm === 'npm' ? 'npm run' : `${options.pm} run`
  c.file('README.md', `# ${options.name}\n\nGenerated by PepperFM Nuxt Starter ${generatorVersion}. Nitro production preset: **bun**.\n\n## Start\n\n\`\`\`sh\n${options.pm} install\n${c.pkg.scripts['services:up'] ? `${run} services:up\n` : ''}${c.has('hub') ? `${run} db:generate\n${run} db:migrate\n` : ''}${run} dev\n\`\`\`\n\nWhen ESLint is selected, normal generation formats the new source after installation. With --no-install, run the generated lint:fix script once after installing manually.\n\nBun runs the app and workers; Node 22+ is also required by the Vue typechecking toolchain. The typecheck command deliberately does not force --bun, and CI verifies it rejects a known error inside a Vue component.\n\nThe generator creates an ignored .env with a unique development auth secret. Never commit .env. If recreating it from .env.example, generate a secret of at least 32 characters. DATABASE_URL and Redis URLs are runtime settings. Configure external services manually when Docker is disabled.\n\n## Selected features\n\nUI: ${options.ui}\n\nModules: ${options.modules.join(', ') || 'none'}\n\nBackend: ${options.features.join(', ') || 'none'}\n\n${[...options.notices, ...c.notes].map(note => `- ${note}`).join('\n')}\n\n## Verify and build\n\n\`\`\`sh\n${run} typecheck\n${c.has('queue') ? `${run} typecheck:worker\n` : ''}${c.has('test') ? `${run} test\n` : ''}${c.has('eslint') ? `${run} lint\n` : ''}${run} build\n${run} start\n\`\`\`\n\n${c.has('queue') ? `## Background work\n\nIn separate terminals run \`${run} worker\` and \`${run} queue:demo\`. Register recurring tasks once with \`${run} schedule:register\`. All run on Bun; queues are not in the HTTP process.\n\n` : ''}${options.deploy ? 'See deploy/README.md for Ubuntu deployment examples. Nothing is deployed automatically.\n\n' : ''}## Ownership\n\nThis is generated application source, not a runtime dependency on the generator. Commit the installed lockfile and review dependency updates in CI. The starter is a foundation, not a turnkey production security or delivery policy.\n`)
  c.file('.github/workflows/ci.yml', `name: Application checks
on: [push, pull_request]
permissions:
  contents: read
jobs:
  checks:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
      - uses: actions/setup-node@v4
        with:
          node-version: '22'
      - uses: oven-sh/setup-bun@v2
      - run: bun install --frozen-lockfile
      - run: bun run typecheck
${c.has('queue') ? '      - run: bun run typecheck:worker\n' : ''}${c.has('test') ? '      - run: bun run test\n' : ''}${c.has('eslint') ? '      - run: bun run lint\n' : ''}      - run: bun run build
`)
  // Generated CI targets the default Bun workflow. npm/pnpm users should update it alongside their lockfile.
  return { files: c.files, notices: [...options.notices, ...c.notes], config: c.cfg, pkg: c.pkg }
}

export async function writeProject(options, plan = buildProject(options)) {
  if (options.dryRun) return plan
  // Validate every path before the first write. Recipes are local and trusted, but mistakes must not escape the target.
  for (const path of plan.files.keys()) {
    const rel = relative(options.dir, resolve(options.dir, path))
    if (!rel || rel.startsWith('..') || isAbsolute(path)) throw new Error(`Unsafe recipe path: ${path}`)
  }
  await mkdir(dirname(options.dir), { recursive: true })
  try { await mkdir(options.dir) }
  catch (error) {
    if (error.code === 'EEXIST') throw new Error(`Destination already exists: ${options.dir}. No files were overwritten.`)
    throw error
  }
  try {
    for (const [path, content] of plan.files) {
      const absolute = resolve(options.dir, path)
      await mkdir(dirname(absolute), { recursive: true })
      await writeFile(absolute, content, { flag: 'wx' })
    }
    const env = plan.files.get('.env.example').replace(/^NUXT_AUTH_SECRET=$/m, `NUXT_AUTH_SECRET=${randomBytes(48).toString('base64url')}`)
    await writeFile(resolve(options.dir, '.env'), env, { flag: 'wx', mode: 0o600 })
    await chmod(resolve(options.dir, '.env'), 0o600)
  } catch (error) {
    throw new Error(`Generation stopped. Partial files remain at ${options.dir}; nothing was deleted. ${error.message}`, { cause: error })
  }
  return plan
}

export async function run(command, args, cwd) {
  await new Promise((accept, reject) => {
    const child = spawn(command, args, { cwd, stdio: 'inherit', shell: false })
    child.once('error', error => reject(new Error(`Cannot run ${command}: ${error.message}`, { cause: error })))
    child.once('exit', (code, signal) => code === 0 ? accept() : reject(new Error(`${command} failed (${signal ?? code}). Generated files were preserved.`)))
  })
}
export async function finishProject(options, execute = run) {
  if (options.dryRun) return
  if (options.install) {
    await execute(options.pm, ['install'], options.dir)
    // Match the consumer's first CI run: generated source must already satisfy its ESLint preset.
    if (options.modules.includes('eslint')) await execute(options.pm, ['run', 'lint:fix'], options.dir)
  }
  if (options.git) await execute('git', ['init', '-b', 'master'], options.dir)
}
